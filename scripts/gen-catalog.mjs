#!/usr/bin/env node
// Generates src/providers/catalog.ts from https://models.dev/api.json.
//
// Usage: node scripts/gen-catalog.mjs [--url <url>] [--out <path>]
//
// The output is deterministic for a given payload except for `generatedAt`:
// providers and models are sorted by id so diffs stay reviewable.

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_URL = "https://models.dev/api.json";
const DEFAULT_OUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src/providers/catalog.ts",
);

function parseArgs(argv) {
  let url = DEFAULT_URL;
  let out = DEFAULT_OUT;
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--url" && argv[i + 1] !== undefined) {
      url = argv[i + 1];
      i += 1;
    } else if (arg === "--out" && argv[i + 1] !== undefined) {
      out = resolve(argv[i + 1]);
      i += 1;
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }
  return { url, out };
}

function compareIds(a, b) {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
}

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function str(value, field, where) {
  if (typeof value !== "string") {
    throw new Error(`${where}: expected string for ${field}, got ${typeof value}`);
  }
  return value;
}

function optStr(value, field, where) {
  return value === undefined || value === null ? undefined : str(value, field, where);
}

function optNum(value, field, where) {
  if (value === undefined || value === null) return undefined;
  if (typeof value !== "number" || !Number.isFinite(value)) {
    throw new Error(`${where}: expected finite number for ${field}, got ${typeof value}`);
  }
  return value;
}

function optBool(value, field, where) {
  if (value === undefined || value === null) return undefined;
  if (typeof value !== "boolean") {
    throw new Error(`${where}: expected boolean for ${field}, got ${typeof value}`);
  }
  return value;
}

/** Copies only defined keys, preserving the declared field order. */
function compact(entries) {
  const out = {};
  for (const [key, value] of entries) {
    if (value !== undefined) out[key] = value;
  }
  return out;
}

function normalizeModel(raw, where) {
  if (!isRecord(raw)) throw new Error(`${where}: model is not an object`);
  const limit = isRecord(raw.limit) ? raw.limit : {};
  const cost = isRecord(raw.cost) ? raw.cost : {};
  return compact([
    ["id", str(raw.id, "id", where)],
    ["name", str(raw.name, "name", where)],
    ["family", optStr(raw.family, "family", where)],
    ["context", optNum(limit.context, "limit.context", where)],
    ["output", optNum(limit.output, "limit.output", where)],
    ["inputCost", optNum(cost.input, "cost.input", where)],
    ["outputCost", optNum(cost.output, "cost.output", where)],
    ["reasoning", optBool(raw.reasoning, "reasoning", where)],
    ["toolCall", optBool(raw.tool_call, "tool_call", where)],
    ["attachment", optBool(raw.attachment, "attachment", where)],
    ["knowledge", optStr(raw.knowledge, "knowledge", where)],
    ["releaseDate", optStr(raw.release_date, "release_date", where)],
    ["status", optStr(raw.status, "status", where)],
  ]);
}

function normalizeProvider(raw, fallbackId) {
  if (!isRecord(raw)) throw new Error(`provider ${fallbackId}: not an object`);
  const id = str(raw.id ?? fallbackId, "id", `provider ${fallbackId}`);
  if (id !== fallbackId) {
    throw new Error(`provider ${fallbackId}: id mismatch (${id})`);
  }
  if (!isRecord(raw.models)) {
    throw new Error(`provider ${id}: models is not an object`);
  }
  const env = raw.env;
  if (!Array.isArray(env) || env.some((value) => typeof value !== "string")) {
    throw new Error(`provider ${id}: env must be an array of strings`);
  }
  const models = {};
  for (const modelId of Object.keys(raw.models).sort(compareIds)) {
    const model = normalizeModel(raw.models[modelId], `${id}/${modelId}`);
    if (model.id !== modelId) {
      throw new Error(`${id}/${modelId}: model id mismatch (${model.id})`);
    }
    models[modelId] = model;
  }
  return compact([
    ["id", id],
    ["name", str(raw.name, "name", `provider ${id}`)],
    ["env", env],
    ["api", optStr(raw.api, "api", `provider ${id}`)],
    ["doc", optStr(raw.doc, "doc", `provider ${id}`)],
    ["npm", str(raw.npm, "npm", `provider ${id}`)],
    ["models", models],
  ]);
}

function render(catalog) {
  const lines = [
    "// Generated by scripts/gen-catalog.mjs — do not edit by hand.",
    "// Source: https://models.dev/api.json",
    'import type { Catalog } from "./types.js";',
    "",
    "export const CATALOG: Catalog = {",
    `  generatedAt: ${JSON.stringify(catalog.generatedAt)},`,
    `  source: ${JSON.stringify(catalog.source)},`,
    "  providers: {",
  ];
  for (const provider of Object.values(catalog.providers)) {
    const head = compact([
      ["id", provider.id],
      ["name", provider.name],
      ["env", provider.env],
      ["api", provider.api],
      ["doc", provider.doc],
      ["npm", provider.npm],
    ]);
    lines.push(`    ${JSON.stringify(provider.id)}: {`);
    for (const [key, value] of Object.entries(head)) {
      lines.push(`      ${key}: ${JSON.stringify(value)},`);
    }
    lines.push("      models: {");
    for (const model of Object.values(provider.models)) {
      lines.push(`        ${JSON.stringify(model.id)}: ${JSON.stringify(model)},`);
    }
    lines.push("      },");
    lines.push("    },");
  }
  lines.push("  },", "};", "");
  return lines.join("\n");
}

async function main() {
  const { url, out } = parseArgs(process.argv.slice(2));
  process.stderr.write(`fetching ${url}\n`);
  const res = await fetch(url, {
    headers: { accept: "application/json", "user-agent": "roan-cli-catalog-generator" },
  });
  if (!res.ok) {
    throw new Error(`fetch failed: ${res.status} ${res.statusText}`);
  }
  const payload = await res.json();
  if (!isRecord(payload)) throw new Error("payload is not an object keyed by provider id");

  const providers = {};
  for (const providerId of Object.keys(payload).sort(compareIds)) {
    providers[providerId] = normalizeProvider(payload[providerId], providerId);
  }

  const catalog = {
    generatedAt: new Date().toISOString(),
    source: url,
    providers,
  };
  const providerCount = Object.keys(providers).length;
  const modelCount = Object.values(providers).reduce(
    (total, provider) => total + Object.keys(provider.models).length,
    0,
  );
  if (providerCount === 0 || modelCount === 0) {
    throw new Error("refusing to write an empty catalog");
  }

  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, render(catalog), "utf8");
  process.stderr.write(
    `wrote ${out} (${providerCount} providers, ${modelCount} models)\n`,
  );
}

main().catch((error) => {
  process.stderr.write(`gen-catalog failed: ${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
